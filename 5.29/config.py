# 电机停止 PWM 预留值。
# 当前主线程真正下发的是 target_speed 这种速度级命令，不直接使用这个值，
# 但它保留下来是为了后续如果改成更底层 PWM 控制时方便接。
MOTOR_STOP = 2000

# 电机最大速度预留值。
